using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;
using TechCosmos.Metrology;

namespace TechCosmos.Metrology.Editor
{
    static class MeasureUnitGenerator
    {
        public static MeasureUnitSO Create(string unitId, float editorUnits, float definedUnits)
        {
            MeasureUnitId.EnsureValid(unitId);
            if (Find(unitId) != null)
                throw new System.InvalidOperationException($"单位「{unitId}」已经存在。");

            MeasureFolders.Ensure(MeasurePaths.UnitFolder);
            MeasureFolders.Ensure(MeasurePaths.GeneratedFolder);

            var unit = ScriptableObject.CreateInstance<MeasureUnitSO>();
            unit.Initialize(unitId, editorUnits, definedUnits);
            unit.name = unitId;
            AssetDatabase.CreateAsset(unit, AssetPath(unitId));
            WriteClass(unitId);
            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
            MeasureCatalogSync.Rewrite(MeasureCatalogSync.Scan());
            return unit;
        }

        public static void WriteClass(string unitId)
        {
            MeasureUnitId.EnsureValid(unitId);
            MeasureFolders.Ensure(MeasurePaths.GeneratedFolder);
            var path = ClassPath(unitId);
            File.WriteAllText(path, BuildClass(unitId), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
            AssetDatabase.ImportAsset(path);
        }

        public static void Delete(MeasureUnitSO unit)
        {
            if (unit == null)
                return;

            var unitId = unit.UnitId;
            var assetPath = AssetDatabase.GetAssetPath(unit);
            if (!string.IsNullOrEmpty(assetPath))
                AssetDatabase.DeleteAsset(assetPath);
            AssetDatabase.Refresh();

            if (MeasureUnitId.IsValid(unitId) && Find(unitId) == null)
                DeleteClassFile(ClassPath(unitId));

            AssetDatabase.Refresh();
            MeasureCatalogSync.Rewrite(MeasureCatalogSync.Scan());
        }

        public static MeasureUnitSO Find(string unitId)
        {
            foreach (var unit in MeasureCatalogSync.Scan())
            {
                if (unit.UnitId == unitId)
                    return unit;
            }
            return null;
        }

        public static bool ClassExists(string unitId)
        {
            return MeasureUnitId.IsValid(unitId) && File.Exists(ClassPath(unitId));
        }

        public static string ClassPath(string unitId) => $"{MeasurePaths.GeneratedFolder}/{unitId}.cs";

        static void DeleteClassFile(string classPath)
        {
            if (!File.Exists(classPath))
                return;
            if (AssetDatabase.DeleteAsset(classPath))
                return;
            File.Delete(classPath);
            var metaPath = classPath + ".meta";
            if (File.Exists(metaPath))
                File.Delete(metaPath);
        }

        static string AssetPath(string unitId) => $"{MeasurePaths.UnitFolder}/{unitId}.asset";

        static string BuildClass(string unitId)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// 由度量衡主控面板生成。比例在同名的单位资源上，不要在这个文件里改数。");
            sb.AppendLine("using TechCosmos.Metrology;");
            sb.AppendLine();
            sb.AppendLine("/// <summary>项目定义的度量单位。换算读取它自己的全局比例。</summary>");
            sb.AppendLine($"public static class {unitId}");
            sb.AppendLine("{");
            sb.AppendLine($"    public const string UnitId = \"{unitId}\";");
            sb.AppendLine();
            sb.AppendLine("    public static float ToDefined(float editorLength) => MeasureUnits.Require(UnitId).ToDefined(editorLength);");
            sb.AppendLine();
            sb.AppendLine("    public static float ToEditor(float definedValue) => MeasureUnits.Require(UnitId).ToEditor(definedValue);");
            sb.AppendLine("}");
            return sb.ToString();
        }
    }
}
